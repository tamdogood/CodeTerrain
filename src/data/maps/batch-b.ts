type RepositoryKey = keyof typeof repositories;

function cite(repo: RepositoryKey, path: string, label: string) {
  const [owner, name, commit] = repositories[repo];
  return {
    label,
    path,
    url: `https://github.com/${owner}/${name}/blob/${commit}/${path}`,
  };
}

